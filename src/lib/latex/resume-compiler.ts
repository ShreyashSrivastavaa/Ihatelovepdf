/**
 * LaTeX Resume Compiler & Document Generator
 * Compiles structured resume data into authentic LaTeX source code and
 * pixel-perfect ATS-friendly vector PDF DocumentModels.
 */

import {
  ResumeData,
  ResumeTemplateId,
  RESUME_TEMPLATES,
} from './resume-types';
import {
  DocumentModel,
  PageModel,
  CanvasElement,
  buildPdfFromDocumentModel,
} from '../pdf-engine/creator-engine';

/**
 * Escapes special LaTeX characters
 */
function escapeLatex(text: string): string {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/&/g, '\\&')
    .replace(/%/g, '\\%')
    .replace(/\$/g, '\\$')
    .replace(/#/g, '\\#')
    .replace(/_/g, '\\_')
    .replace(/{/g, '\\{')
    .replace(/}/g, '\\}')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

/**
 * Generates compilable, standard LaTeX source code for the given resume
 */
export function generateLatexSource(data: ResumeData, templateId: ResumeTemplateId = 'jakes'): string {
  const p = data.personalInfo;
  const isSerif = templateId === 'corporate' || templateId === 'academic';

  let tex = `%-------------------------\n`;
  tex += `% Resume in LaTeX\n`;
  tex += `% Template: ${RESUME_TEMPLATES.find((t) => t.id === templateId)?.name || 'ATS Friendly'}\n`;
  tex += `% Generated by PDFLince (https://ihatelovepdf.com)\n`;
  tex += `%-------------------------\n\n`;

  tex += `\\documentclass[letterpaper,10pt]{article}\n\n`;
  tex += `\\usepackage{latexsym}\n`;
  tex += `\\usepackage[empty]{fullpage}\n`;
  tex += `\\usepackage{titlesec}\n`;
  tex += `\\usepackage{marvosym}\n`;
  tex += `\\usepackage[usenames,dvipsnames]{color}\n`;
  tex += `\\usepackage{verbatim}\n`;
  tex += `\\usepackage{enumitem}\n`;
  tex += `\\usepackage[hidelinks]{hyperref}\n`;
  tex += `\\usepackage{fancyhdr}\n`;
  tex += `\\usepackage[english]{babel}\n`;
  tex += `\\usepackage{tabularx}\n\n`;

  if (!isSerif) {
    tex += `% Sans-Serif Font Setup\n`;
    tex += `\\usepackage[default]{sourcesanspro}\n`;
    tex += `\\urlstyle{same}\n\n`;
  }

  tex += `\\pagestyle{fancy}\n`;
  tex += `\\fancyhf{}\n`;
  tex += `\\renewcommand{\\headrulewidth}{0pt}\n`;
  tex += `\\renewcommand{\\footrulewidth}{0pt}\n\n`;

  tex += `% Adjust margins\n`;
  tex += `\\addtolength{\\oddsidemargin}{-0.5in}\n`;
  tex += `\\addtolength{\\evensidemargin}{-0.5in}\n`;
  tex += `\\addtolength{\\textwidth}{1in}\n`;
  tex += `\\addtolength{\\topmargin}{-.5in}\n`;
  tex += `\\addtolength{\\textheight}{1.0in}\n\n`;

  tex += `% Section formatting\n`;
  tex += `\\titleformat{\\section}{\n`;
  tex += `  \\vspace{-4pt}\\scshape\\raggedright\\large\n`;
  tex += `}{}{0em}{}[\\color{black}\\titlerule \\vspace{-5pt}]\n\n`;

  tex += `% Custom commands\n`;
  tex += `\\newcommand{\\resumeItem}[1]{\\item\\small{#1 \\vspace{-2pt}}}\n`;
  tex += `\\newcommand{\\resumeSubheading}[4]{\n`;
  tex += `  \\vspace{-2pt}\\item\n`;
  tex += `    \\begin{tabular*}{0.97\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}\n`;
  tex += `      \\textbf{#1} & #2 \\\\\n`;
  tex += `      \\textit{\\small#3} & \\textit{\\small #4} \\\\\n`;
  tex += `    \\end{tabular*}\\vspace{-7pt}\n`;
  tex += `}\n`;
  tex += `\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}\n`;
  tex += `\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}\n`;
  tex += `\\newcommand{\\resumeItemListStart}{\\begin{itemize}[leftmargin=0.2in]}\n`;
  tex += `\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{-5pt}}\n\n`;

  tex += `\\begin{document}\n\n`;

  // --- Header ---
  tex += `%----------HEADING----------\n`;
  tex += `\\begin{center}\n`;
  tex += `    \\textbf{\\Huge \\scshape ${escapeLatex(p.name || 'Your Name')}} \\\\ \\vspace{1pt}\n`;

  const contactItems: string[] = [];
  if (p.phone) contactItems.push(`\\small ${escapeLatex(p.phone)}`);
  if (p.email) contactItems.push(`\\href{mailto:${p.email}}{\\underline{${escapeLatex(p.email)}}}`);
  if (p.location) contactItems.push(`${escapeLatex(p.location)}`);
  if (p.linkedin) contactItems.push(`\\href{https://${p.linkedin}}{\\underline{${escapeLatex(p.linkedin)}}}`);
  if (p.github) contactItems.push(`\\href{https://${p.github}}{\\underline{${escapeLatex(p.github)}}}`);
  if (p.portfolio) contactItems.push(`\\href{https://${p.portfolio}}{\\underline{${escapeLatex(p.portfolio)}}}`);

  tex += `    ${contactItems.join(' $|$ ')}\n`;
  tex += `\\end{center}\n\n`;

  // --- Summary ---
  if (data.summary) {
    tex += `%-----------SUMMARY-----------\n`;
    tex += `\\section{Professional Summary}\n`;
    tex += `\\small{${escapeLatex(data.summary)}}\n\n`;
  }

  // --- Education ---
  if (data.education && data.education.length > 0) {
    tex += `%-----------EDUCATION-----------\n`;
    tex += `\\section{Education}\n`;
    tex += `  \\resumeSubHeadingListStart\n`;
    for (const edu of data.education) {
      const dates = [edu.startDate, edu.endDate].filter(Boolean).join(' -- ');
      tex += `    \\resumeSubheading\n`;
      tex += `      {${escapeLatex(edu.institution)}}{${escapeLatex(edu.location)}}\n`;
      tex += `      {${escapeLatex(edu.degree)}}{${escapeLatex(dates)}}\n`;
      if (edu.gpa || (edu.highlights && edu.highlights.length > 0)) {
        tex += `    \\resumeItemListStart\n`;
        if (edu.gpa) {
          tex += `      \\resumeItem{GPA: ${escapeLatex(edu.gpa)}}\n`;
        }
        if (edu.highlights) {
          for (const h of edu.highlights) {
            tex += `      \\resumeItem{${escapeLatex(h)}}\n`;
          }
        }
        tex += `    \\resumeItemListEnd\n`;
      }
    }
    tex += `  \\resumeSubHeadingListEnd\n\n`;
  }

  // --- Experience ---
  if (data.experience && data.experience.length > 0) {
    tex += `%-----------EXPERIENCE-----------\n`;
    tex += `\\section{Experience}\n`;
    tex += `  \\resumeSubHeadingListStart\n`;
    for (const exp of data.experience) {
      const dates = [exp.startDate, exp.endDate].filter(Boolean).join(' -- ');
      tex += `    \\resumeSubheading\n`;
      tex += `      {${escapeLatex(exp.role)}}{${escapeLatex(dates)}}\n`;
      tex += `      {${escapeLatex(exp.company)}}{${escapeLatex(exp.location)}}\n`;
      if (exp.bullets && exp.bullets.length > 0) {
        tex += `      \\resumeItemListStart\n`;
        for (const bullet of exp.bullets) {
          tex += `        \\resumeItem{${escapeLatex(bullet)}}\n`;
        }
        tex += `      \\resumeItemListEnd\n`;
      }
    }
    tex += `  \\resumeSubHeadingListEnd\n\n`;
  }

  // --- Projects ---
  if (data.projects && data.projects.length > 0) {
    tex += `%-----------PROJECTS-----------\n`;
    tex += `\\section{Projects}\n`;
    tex += `  \\resumeSubHeadingListStart\n`;
    for (const proj of data.projects) {
      tex += `    \\resumeSubheading\n`;
      tex += `      {${escapeLatex(proj.name)} $|$ \\emph{\\small ${escapeLatex(proj.technologies)}}}{${escapeLatex(proj.link || '')}}\n`;
      tex += `      {}{}\n`;
      if (proj.bullets && proj.bullets.length > 0) {
        tex += `      \\resumeItemListStart\n`;
        for (const bullet of proj.bullets) {
          tex += `        \\resumeItem{${escapeLatex(bullet)}}\n`;
        }
        tex += `      \\resumeItemListEnd\n`;
      }
    }
    tex += `  \\resumeSubHeadingListEnd\n\n`;
  }

  // --- Technical Skills ---
  if (data.skills && data.skills.length > 0) {
    tex += `%-----------TECHNICAL SKILLS-----------\n`;
    tex += `\\section{Technical Skills}\n`;
    tex += ` \\begin{itemize}[leftmargin=0.15in, label={}]\n`;
    tex += `    \\small{\\item{\n`;
    const skillLines = data.skills.map((s) => `     \\textbf{${escapeLatex(s.name)}}: ${escapeLatex(s.skills)}`);
    tex += `${skillLines.join(' \\\\\n')}\n`;
    tex += `    }}\n`;
    tex += ` \\end{itemize}\n\n`;
  }

  // --- Certifications ---
  if (data.certifications && data.certifications.length > 0) {
    tex += `%-----------CERTIFICATIONS-----------\n`;
    tex += `\\section{Certifications}\n`;
    tex += ` \\begin{itemize}[leftmargin=0.15in, label={}]\n`;
    tex += `    \\small{\\item{\n`;
    const certLines = data.certifications.map((c) => `     \\textbf{${escapeLatex(c.name)}} -- ${escapeLatex(c.issuer)} (${escapeLatex(c.date)})`);
    tex += `${certLines.join(' \\\\\n')}\n`;
    tex += `    }}\n`;
    tex += ` \\end{itemize}\n\n`;
  }

  tex += `\\end{document}\n`;

  return tex;
}

/**
 * Compiles ResumeData into a DocumentModel for our shared PDF Creator Engine
 */
export function compileResumeToDocumentModel(
  data: ResumeData,
  templateId: ResumeTemplateId = 'jakes'
): DocumentModel {
  const p = data.personalInfo;
  const isSerif = templateId === 'corporate' || templateId === 'academic';
  const fontFamily = isSerif ? 'Times' : 'Helvetica';

  // Standard Letter dimensions in points
  const pageWidth = 612.0;
  const pageHeight = 792.0;
  const marginX = 36.0; // 0.5 in
  const contentWidth = pageWidth - marginX * 2;
  const bottomMargin = 40.0;

  const pages: PageModel[] = [];
  let currentElements: CanvasElement[] = [];
  let cursorY = 36.0;

  const startNewPage = () => {
    pages.push({
      id: `page_${pages.length + 1}`,
      format: 'letter',
      orientation: 'portrait',
      elements: currentElements,
    });
    currentElements = [];
    cursorY = 36.0;
  };

  const ensureSpace = (neededHeight: number) => {
    if (cursorY + neededHeight > pageHeight - bottomMargin) {
      startNewPage();
    }
  };

  // Helper to add a section header with horizontal line
  const addSectionHeader = (title: string) => {
    ensureSpace(28);
    cursorY += 8;

    currentElements.push({
      id: `sec_${title}_${Date.now()}_${Math.random()}`,
      type: 'text',
      text: title.toUpperCase(),
      x: marginX,
      y: cursorY,
      width: contentWidth,
      height: 14,
      font: fontFamily,
      fontSize: 11,
      bold: true,
      color: '#0f172a',
      alignment: 'left',
    });
    cursorY += 13;

    // Horizontal divider rule
    currentElements.push({
      id: `sec_line_${title}_${Date.now()}_${Math.random()}`,
      type: 'shape',
      shapeType: 'line',
      x: marginX,
      y: cursorY,
      width: contentWidth,
      height: 0,
      strokeColor: '#334155',
      strokeWidth: 0.75,
    });
    cursorY += 6;
  };

  // 1. Header (Name & Contact)
  ensureSpace(50);
  currentElements.push({
    id: `hdr_name_${Date.now()}`,
    type: 'text',
    text: p.name || 'Your Name',
    x: marginX,
    y: cursorY,
    width: contentWidth,
    height: 24,
    font: fontFamily,
    fontSize: 20,
    bold: true,
    color: '#0f172a',
    alignment: templateId === 'modern' ? 'left' : 'center',
  });
  cursorY += 24;

  const contactList: string[] = [];
  if (p.phone) contactList.push(p.phone);
  if (p.email) contactList.push(p.email);
  if (p.location) contactList.push(p.location);
  if (p.linkedin) contactList.push(p.linkedin.replace(/^https?:\/\//, ''));
  if (p.github) contactList.push(p.github.replace(/^https?:\/\//, ''));
  if (p.portfolio) contactList.push(p.portfolio.replace(/^https?:\/\//, ''));

  if (contactList.length > 0) {
    currentElements.push({
      id: `hdr_contact_${Date.now()}`,
      type: 'text',
      text: contactList.join('  •  '),
      x: marginX,
      y: cursorY,
      width: contentWidth,
      height: 12,
      font: fontFamily,
      fontSize: 8.5,
      color: '#475569',
      alignment: templateId === 'modern' ? 'left' : 'center',
    });
    cursorY += 14;
  }

  // 2. Summary
  if (data.summary) {
    addSectionHeader('Summary');
    ensureSpace(30);
    currentElements.push({
      id: `summary_text_${Date.now()}`,
      type: 'text',
      text: data.summary,
      x: marginX,
      y: cursorY,
      width: contentWidth,
      height: 28,
      font: fontFamily,
      fontSize: 9,
      lineHeight: 1.25,
      color: '#1e293b',
      alignment: 'left',
    });
    cursorY += 32;
  }

  // 3. Education
  if (data.education && data.education.length > 0) {
    addSectionHeader('Education');
    for (const edu of data.education) {
      ensureSpace(28);
      const dates = [edu.startDate, edu.endDate].filter(Boolean).join(' – ');

      // School & Dates row
      currentElements.push({
        id: `edu_inst_${edu.id}`,
        type: 'text',
        text: edu.institution,
        x: marginX,
        y: cursorY,
        width: contentWidth - 140,
        height: 12,
        font: fontFamily,
        fontSize: 10,
        bold: true,
        color: '#0f172a',
      });
      if (dates) {
        currentElements.push({
          id: `edu_dates_${edu.id}`,
          type: 'text',
          text: dates,
          x: marginX + contentWidth - 140,
          y: cursorY,
          width: 140,
          height: 12,
          font: fontFamily,
          fontSize: 9,
          color: '#475569',
          alignment: 'right',
        });
      }
      cursorY += 12;

      // Degree & Location row
      currentElements.push({
        id: `edu_deg_${edu.id}`,
        type: 'text',
        text: edu.degree,
        x: marginX,
        y: cursorY,
        width: contentWidth - 140,
        height: 11,
        font: fontFamily,
        fontSize: 9,
        italic: true,
        color: '#334155',
      });
      if (edu.location) {
        currentElements.push({
          id: `edu_loc_${edu.id}`,
          type: 'text',
          text: edu.location,
          x: marginX + contentWidth - 140,
          y: cursorY,
          width: 140,
          height: 11,
          font: fontFamily,
          fontSize: 8.5,
          italic: true,
          color: '#475569',
          alignment: 'right',
        });
      }
      cursorY += 12;

      // GPA or highlights
      if (edu.gpa) {
        ensureSpace(12);
        currentElements.push({
          id: `edu_gpa_${edu.id}`,
          type: 'text',
          text: `GPA: ${edu.gpa}`,
          x: marginX + 12,
          y: cursorY,
          width: contentWidth - 12,
          height: 10,
          font: fontFamily,
          fontSize: 8.5,
          color: '#334155',
        });
        cursorY += 11;
      }
      cursorY += 3;
    }
  }

  // 4. Experience
  if (data.experience && data.experience.length > 0) {
    addSectionHeader('Experience');
    for (const exp of data.experience) {
      ensureSpace(32);
      const dates = [exp.startDate, exp.endDate].filter(Boolean).join(' – ');

      // Role & Dates
      currentElements.push({
        id: `exp_role_${exp.id}`,
        type: 'text',
        text: exp.role,
        x: marginX,
        y: cursorY,
        width: contentWidth - 140,
        height: 12,
        font: fontFamily,
        fontSize: 10,
        bold: true,
        color: '#0f172a',
      });
      if (dates) {
        currentElements.push({
          id: `exp_dates_${exp.id}`,
          type: 'text',
          text: dates,
          x: marginX + contentWidth - 140,
          y: cursorY,
          width: 140,
          height: 12,
          font: fontFamily,
          fontSize: 9,
          bold: true,
          color: '#334155',
          alignment: 'right',
        });
      }
      cursorY += 12;

      // Company & Location
      currentElements.push({
        id: `exp_comp_${exp.id}`,
        type: 'text',
        text: exp.company,
        x: marginX,
        y: cursorY,
        width: contentWidth - 140,
        height: 11,
        font: fontFamily,
        fontSize: 9,
        italic: true,
        color: '#334155',
      });
      if (exp.location) {
        currentElements.push({
          id: `exp_loc_${exp.id}`,
          type: 'text',
          text: exp.location,
          x: marginX + contentWidth - 140,
          y: cursorY,
          width: 140,
          height: 11,
          font: fontFamily,
          fontSize: 8.5,
          italic: true,
          color: '#475569',
          alignment: 'right',
        });
      }
      cursorY += 13;

      // Bullets
      if (exp.bullets) {
        for (const bullet of exp.bullets) {
          ensureSpace(14);
          // Bullet point icon
          currentElements.push({
            id: `exp_bullet_pt_${exp.id}_${Math.random()}`,
            type: 'text',
            text: '•',
            x: marginX + 6,
            y: cursorY,
            width: 8,
            height: 10,
            font: fontFamily,
            fontSize: 8.5,
            color: '#0f172a',
          });
          // Bullet point text
          currentElements.push({
            id: `exp_bullet_txt_${exp.id}_${Math.random()}`,
            type: 'text',
            text: bullet,
            x: marginX + 16,
            y: cursorY,
            width: contentWidth - 16,
            height: 12,
            font: fontFamily,
            fontSize: 8.5,
            lineHeight: 1.25,
            color: '#1e293b',
          });
          cursorY += 13;
        }
      }
      cursorY += 4;
    }
  }

  // 5. Projects
  if (data.projects && data.projects.length > 0) {
    addSectionHeader('Projects');
    for (const proj of data.projects) {
      ensureSpace(26);

      const titleText = proj.technologies ? `${proj.name}  |  ${proj.technologies}` : proj.name;
      currentElements.push({
        id: `proj_title_${proj.id}`,
        type: 'text',
        text: titleText,
        x: marginX,
        y: cursorY,
        width: contentWidth - 120,
        height: 12,
        font: fontFamily,
        fontSize: 9.5,
        bold: true,
        color: '#0f172a',
      });
      if (proj.link) {
        currentElements.push({
          id: `proj_link_${proj.id}`,
          type: 'text',
          text: proj.link.replace(/^https?:\/\//, ''),
          x: marginX + contentWidth - 120,
          y: cursorY,
          width: 120,
          height: 11,
          font: fontFamily,
          fontSize: 8.5,
          color: '#2563eb',
          alignment: 'right',
        });
      }
      cursorY += 12;

      if (proj.bullets) {
        for (const bullet of proj.bullets) {
          ensureSpace(14);
          currentElements.push({
            id: `proj_bullet_pt_${proj.id}_${Math.random()}`,
            type: 'text',
            text: '•',
            x: marginX + 6,
            y: cursorY,
            width: 8,
            height: 10,
            font: fontFamily,
            fontSize: 8.5,
            color: '#0f172a',
          });
          currentElements.push({
            id: `proj_bullet_txt_${proj.id}_${Math.random()}`,
            type: 'text',
            text: bullet,
            x: marginX + 16,
            y: cursorY,
            width: contentWidth - 16,
            height: 12,
            font: fontFamily,
            fontSize: 8.5,
            lineHeight: 1.25,
            color: '#1e293b',
          });
          cursorY += 13;
        }
      }
      cursorY += 4;
    }
  }

  // 6. Skills
  if (data.skills && data.skills.length > 0) {
    addSectionHeader('Technical Skills');
    for (const skill of data.skills) {
      ensureSpace(14);
      currentElements.push({
        id: `skill_${skill.id}`,
        type: 'text',
        text: `${skill.name}: ${skill.skills}`,
        x: marginX,
        y: cursorY,
        width: contentWidth,
        height: 11,
        font: fontFamily,
        fontSize: 9,
        bold: true,
        color: '#0f172a',
      });
      cursorY += 13;
    }
    cursorY += 4;
  }

  // 7. Certifications
  if (data.certifications && data.certifications.length > 0) {
    addSectionHeader('Certifications');
    for (const cert of data.certifications) {
      ensureSpace(14);
      currentElements.push({
        id: `cert_${cert.id}`,
        type: 'text',
        text: `•  ${cert.name} – ${cert.issuer} (${cert.date})`,
        x: marginX + 6,
        y: cursorY,
        width: contentWidth - 6,
        height: 11,
        font: fontFamily,
        fontSize: 8.5,
        color: '#1e293b',
      });
      cursorY += 13;
    }
  }

  // Push final page
  pages.push({
    id: `page_${pages.length + 1}`,
    format: 'letter',
    orientation: 'portrait',
    elements: currentElements,
  });

  return {
    title: `${p.name || 'Resume'} - ATS Resume`,
    author: p.name || 'PDFLince LaTeX Builder',
    subject: 'ATS-Friendly Professional Resume',
    pages,
  };
}

/**
 * Builds the PDF bytes directly from resume data using our Creator Engine
 */
export async function generateResumePdf(
  data: ResumeData,
  templateId: ResumeTemplateId = 'jakes'
): Promise<Uint8Array> {
  const model = compileResumeToDocumentModel(data, templateId);
  return buildPdfFromDocumentModel(model);
}
